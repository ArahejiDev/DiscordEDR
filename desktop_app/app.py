        reason = simpledialog.askstring(
            "Motivo del baneo", "Motivo:", initialvalue=description, parent=self)

        queue_action("ban", guild_id, user_id, reason=reason, username=username)
        self.status_var.set(f"Baneo de {username} solicitado. Se ejecutará en unos segundos.")

