class EDRDesktopApp(tk.Tk):
    def __init__(self):
        super().__init__()
        self.title("Discord EDR — Panel de control")
        self.geometry("1150x760")
        self.minsize(900, 600)
        self.protocol("WM_DELETE_WINDOW", self._on_close)

        init_db()
        self.rule_engine = RuleEngine()

        self._build_ui()
        self._start_bot()
        self._refresh_all()
        self.after(REFRESH_MS, self._auto_refresh)
        self.after(BOT_STATUS_MS, self._update_bot_status)

    # ------------------------------------------------------------------
    # Bot lifecycle (bot_runner starts/stops the actual Discord bot on a
    # background thread — the README/run_app.py docstring already promise
    # this happens automatically when the panel opens, this is what wires
    # it up)
    # ------------------------------------------------------------------
    def _start_bot(self):
        ok, message = bot_runner.start_bot()
        self.bot_status_var.set(message if ok else f"Bot: {message}")

    def _update_bot_status(self):
        self.bot_status_var.set(f"Bot: {bot_runner.status_text()}")
        self.after(BOT_STATUS_MS, self._update_bot_status)

    def _on_close(self):
        if bot_runner.is_running():
            bot_runner.stop_bot()
        self.destroy()

