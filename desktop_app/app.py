"""
Desktop panel for the Discord EDR — Discord-style dark theme.

Does not depend on discord.py: it reads directly from the SQLite database
generated by the bot (data/edr.db) and manages the rules file
(data/rules.json) through the same RuleEngine class the bot uses. The bot
can be running and this panel open at the same time with no conflict
(SQLite supports concurrent reads).

Moderation actions (ban, kick, warn) are not executed directly by this
panel: they're queued in the `pending_actions` table via queue_action(),
and it's the bot -which holds the live Discord connection and
permissions- that executes them on its next polling cycle.

Also starts/stops the bot itself (bot_runner.start_bot / stop_bot) on a
background thread, so opening the panel is enough to bring the whole
system up.

Run from the project root:
    python -m desktop_app.app
"""
