    # ------------------------------------------------------------------
    # Helper to keep the selection when a Treeview is refreshed
    # ------------------------------------------------------------------
    def _save_selection(self, tree):
        """Returns the 'values' tuple of the currently selected rows."""
        return [tuple(tree.item(i)["values"]) for i in tree.selection()]

    def _restore_selection(self, tree, saved_values):
        """Reselects the rows whose 'values' match the saved ones."""
        if not saved_values:
            return
        for item in tree.get_children():
            if tuple(tree.item(item)["values"]) in saved_values:
                tree.selection_add(item)

