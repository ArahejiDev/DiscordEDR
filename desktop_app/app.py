    def _auto_refresh(self):
        self._refresh_all()
        self.after(REFRESH_MS, self._auto_refresh)

    def _refresh_all(self):
        try:
            self._refresh_dashboard()
            self._refresh_events()
            self._refresh_members()
            self._refresh_rules_view()
            self._refresh_analytics()
            self.status_var.set("Actualizado correctamente.")
        except Exception as e:
            self.status_var.set(f"Error al refrescar: {e}")

    def _refresh_dashboard(self):
        counts = count_alerts_by_severity()
        for sev, lbl in self.stat_labels.items():
            lbl.config(text=str(counts.get(sev, 0)))

        saved = self._save_selection(self.alerts_tree)
        for item in self.alerts_tree.get_children():
            self.alerts_tree.delete(item)
        for idx, a in enumerate(fetch_alerts(limit=200)):
            item_id = self.alerts_tree.insert(
                "", "end",
                values=(a["timestamp"], a["severity"], a["rule_name"],
                        a["username"] or "-", a["description"]),
            )
            # store user_id/guild_id outside the visible columns, so we
            # can ban/warn directly from the alert
            self.alerts_tree.item(
                item_id,
                tags=(a["severity"], theme.zebra_tag(idx),
                      f"uid:{a['user_id']}", f"gid:{a['guild_id']}")
            )
        self._restore_selection(self.alerts_tree, saved)

        top = top_active_users(5)
        if top:
            self.top_users_var.set(
                "  |  ".join(f"{u['username']} ({u['n']} msgs)" for u in top)
            )
        else:
            self.top_users_var.set("Sin datos todavía.")

    def _refresh_events(self):
        etype = self.event_type_var.get()
        etype = None if etype == "todos" else etype
        search = self.search_var.get().strip() or None

        saved = self._save_selection(self.events_tree)
        for item in self.events_tree.get_children():
            self.events_tree.delete(item)
        for idx, e in enumerate(fetch_events(limit=300, event_type=etype, search=search)):
            self.events_tree.insert(
                "", "end",
                values=(e["timestamp"], e["event_type"], e["username"] or "-",
                        e["channel_id"] or "-", (e["content"] or "")[:200]),
                tags=(theme.zebra_tag(idx),)
            )
        self._restore_selection(self.events_tree, saved)

    def _refresh_members(self):
        saved = self._save_selection(self.members_tree)
        for item in self.members_tree.get_children():
            self.members_tree.delete(item)
        for idx, m in enumerate(fetch_members()):
            tag = "left" if m["left_at"] else ""
            item_id = self.members_tree.insert(
                "", "end",
                values=(m["username"], m["joined_at"] or "-",
                        m["account_created_at"] or "-", m["left_at"] or ""),
            )
            # store user_id/guild_id outside the visible columns, so we
            # can kick/ban/warn the right member
            self.members_tree.item(
                item_id,
                tags=(tag, theme.zebra_tag(idx), f"uid:{m['user_id']}", f"gid:{m['guild_id']}")
            )
        self._restore_selection(self.members_tree, saved)

    def _refresh_rules_view(self):
        self.rule_engine.reload()

        saved_kw = self._save_selection(self.kw_tree)
        for item in self.kw_tree.get_children():
            self.kw_tree.delete(item)
        for idx, r in enumerate(self.rule_engine.list_keywords()):
            self.kw_tree.insert("", "end", values=(
                r["id"], r["word"], r["severity"], "sí" if r["delete_message"] else "no"),
                tags=(theme.zebra_tag(idx),))
        self._restore_selection(self.kw_tree, saved_kw)

        ld = self.rule_engine.rules["link_detection"]
        self.link_enabled_var.set(ld["enabled"])
        self.link_sev_var.set(ld["severity"])
        self.whitelist_label.config(text="Whitelist: " + (", ".join(ld["whitelist_domains"]) or "(vacía)"))

