    def _add_keyword(self):
        word = self.kw_word_var.get().strip()
        if not word:
            messagebox.showwarning("Aviso", "Escribe una palabra antes de añadir la regla.")
            return
        self.rule_engine.add_keyword(word, severity=self.kw_sev_var.get(),
                                      delete_message=self.kw_delete_var.get())
        self.kw_word_var.set("")
        self.kw_delete_var.set(False)
        self._refresh_rules_view()
        self.status_var.set(f"Palabra vigilada '{word}' añadida.")

    def _delete_selected_keyword(self):
        sel = self.kw_tree.selection()
        if not sel:
            return
        rule_id = self.kw_tree.item(sel[0])["values"][0]
        self.rule_engine.remove_keyword(rule_id)
        self._refresh_rules_view()

    def _toggle_links(self):
        self.rule_engine.set_link_detection(
            enabled=self.link_enabled_var.get(), severity=self.link_sev_var.get())
        self.status_var.set("Detección de links actualizada.")

    def _add_whitelist(self):
        domain = self.whitelist_var.get().strip()
        if not domain:
            return
        self.rule_engine.add_whitelist_domain(domain)
        self.whitelist_var.set("")
        self._refresh_rules_view()

    def _add_load_rule(self):
        try:
            max_msgs = int(self.load_max_var.get())
            window = int(self.load_window_var.get())
        except ValueError:
            messagebox.showerror("Error", "Máx. mensajes y ventana deben ser números enteros.")
            return
        self.rule_engine.add_load_rule(
            self.load_scope_var.get(), max_msgs, window, severity=self.load_sev_var.get())
        self._refresh_rules_view()
        self.status_var.set("Regla de carga añadida.")

    def _delete_selected_load(self):
        sel = self.load_tree.selection()
        if not sel:
            return
        rule_id = self.load_tree.item(sel[0])["values"][0]
        self.rule_engine.remove_load_rule(rule_id)
        self._refresh_rules_view()


